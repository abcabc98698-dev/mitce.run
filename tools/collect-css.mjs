// Collect the Astro source's CSS into one readable stylesheet for the Next build.
//
// Order: global.css (with its @imports inlined), then every component's
// <style> block: ui, blog, sections, chrome, layouts, pages. Comments are kept.
//
// Astro scopes component styles; one flat file does not. So every component's
// selectors must start with a class only that component uses. The script
// refuses to write the file when
//   - a root class is styled in two components, or
//   - a component's root class also appears in another component's markup,
// since that is exactly where one component would start restyling another.
//
// :global(...) is unwrapped (in one flat sheet everything is global) and is
// only accepted inside a selector whose root class the component owns, e.g.
// `.prose :global(p)` for the rendered Markdown in ArticleBody.astro.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const A = join(ROOT, 'src');
const OUT = join(ROOT, 'next', 'src', 'styles', 'site.css');
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));

function inline(file) {
  return readFileSync(file, 'utf8').replace(/@import\s+['"](.+?)['"];?/g, (_, p) => inline(join(dirname(file), p)));
}
const unwrapGlobal = (css) => {
  let out = css, prev;
  do { prev = out; out = out.replace(/:global\(((?:[^()]|\([^()]*\))*)\)/g, '$1'); } while (out !== prev);
  return out;
};

// Shared classes from global.css that components may use but never restyle as a root.
const SHARED = /^(t-[\w-]+|balance|sr-only|below-desktop|desktop-only|phone-only|no-phone|tablet-only)$/;

const ORDER = ['components/ui/', 'components/blog/', 'components/sections/', 'components/', 'layouts/', 'pages/'];
const files = walk(A).filter((f) => f.endsWith('.astro'))
  .map((f) => relative(A, f).replace(/\\/g, '/'))
  .sort((a, b) => {
    const ia = ORDER.findIndex((o) => a.startsWith(o)), ib = ORDER.findIndex((o) => b.startsWith(o));
    return ia - ib || a.localeCompare(b);
  });

// Every class token each file writes in its markup (class="..." and the string
// literals of class:list / class={...}).
const markup = new Map();
for (const rel of files) {
  const html = readFileSync(join(A, rel), 'utf8').replace(/<style[^>]*>[\s\S]*?<\/style>/g, '');
  const tokens = new Set();
  for (const a of html.matchAll(/\bclass(?::list)?=(?:"([^"]*)"|\{([\s\S]*?)\}(?=[\s/>]))/g)) {
    const lits = a[1] !== undefined ? [a[1]] : [...a[2].matchAll(/'([^']*)'|`([^`]*)`|"([^"]*)"/g)].map((x) => x[1] ?? x[2] ?? x[3]);
    for (const lit of lits) for (const t of lit.split(/\s+/)) if (t) tokens.add(t.replace(/\$\{.*$/, ''));
  }
  markup.set(rel, tokens);
}

const owners = new Map();
const problems = [];
const parts = ['/* GENERATED by tools/collect-css.mjs from the Astro source. Edit the .astro files, then regenerate. */', inline(join(A, 'styles', 'global.css'))];

for (const rel of files) {
  const src = readFileSync(join(A, rel), 'utf8');
  const blocks = [...src.matchAll(/<style(\s[^>]*)?>([\s\S]*?)<\/style>/g)];
  if (!blocks.length) continue;
  for (const [, attrs = '', raw] of blocks) {
    if (/is:global|define:vars|is:inline/.test(attrs)) problems.push(`${rel}: <style${attrs}> is not allowed`);
    const bare = raw.replace(/\/\*[\s\S]*?\*\//g, '');
    for (const m of bare.matchAll(/(?<=^|[{};])([^{};]+)\{/g)) {
      const sel = m[1].trim();
      if (!sel || /^(from|to|\d+%)/.test(sel) || sel.startsWith('@')) continue;
      for (const one of sel.split(/,(?![^(]*\))/)) {
        const s = one.trim();
        if (!s || /^(from|to|\d+%)$/.test(s)) continue;
        if (s.startsWith(':global(')) { problems.push(`${rel}: :global() as the root of "${s}"`); continue; }
        const cls = unwrapGlobal(s).match(/\.([A-Za-z_][\w-]*)/);
        if (!cls) { problems.push(`${rel}: selector without a component class: "${s}"`); continue; }
        const root = cls[1];
        if (SHARED.test(root)) { problems.push(`${rel}: restyles shared class .${root} in "${s}"`); continue; }
        const prev = owners.get(root);
        if (prev && prev !== rel) problems.push(`.${root} is styled in both ${prev} and ${rel}`);
        else owners.set(root, rel);
      }
    }
    parts.push(`/* ---- ${rel} ---- */\n${unwrapGlobal(raw.trim())}`);
  }
}
for (const [root, rel] of owners) {
  for (const [other, tokens] of markup) if (other !== rel && tokens.has(root)) problems.push(`.${root} (styled by ${rel}) is also used in the markup of ${other}`);
}

if (problems.length) {
  console.error('collect-css refused:\n  ' + [...new Set(problems)].join('\n  '));
  process.exit(1);
}
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, parts.join('\n\n') + '\n');
console.log(`${files.length} components scanned -> ${relative(ROOT, OUT)}`);
